#!/usr/bin/env python3
r"""Cut a contiguous run of labels out of the converted big-endian data image.

The oracle probe links only the handful of translated functions under test, not
the game's 1 MB data image -- so a carrier that reads a real static table fails
at link time with `undefined reference to DATA_007110'. Defining the table by
hand in C would test the hand-written copy instead of the manifest, which is the
one thing the carrier exists to check.

This takes the bytes STRAIGHT OUT of build\data-be\ffedat_be.s, so whatever
convert_static.py decided about byte order is exactly what the 68020 executes.

    python tools\oracle\extract_data_slice.py DATA_007106 DATA_007116 \
        -o build\xlat\DATA_systable.s

Emits every line from the first label's `xdef' up to and including the last
label's data, into `section ffedat,data' -- the same section name the full image
uses, so nothing about placement changes when the probe is replaced by the real
game. Refuses unless both labels are found exactly once, in that order: a
silently short slice would read as "the table is empty" and pass a test that
proves nothing.
"""
import argparse
import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "build", "data-be", "ffedat_be.s")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("first")
    ap.add_argument("last")
    ap.add_argument("-o", "--out", required=True)
    ap.add_argument("--src", default=SRC)
    a = ap.parse_args()

    if not os.path.exists(a.src):
        print("MISSING %s -- run python tools\\datamap\\convert_static.py" % a.src)
        return 1
    lines = io.open(a.src, encoding="utf-8").read().splitlines()

    def find(label):
        hits = [i for i, l in enumerate(lines) if l == label + ":"]
        if len(hits) != 1:
            print("REFUSING: %s appears %d times in %s"
                  % (label, len(hits), a.src))
            return None
        return hits[0]

    i0, i1 = find(a.first), find(a.last)
    if i0 is None or i1 is None:
        return 1
    if i1 <= i0:
        print("REFUSING: %s comes before %s" % (a.last, a.first))
        return 1

    # Back up over the `xdef' that precedes the first label, and run forward to
    # the line before the NEXT label definition after `last'.
    start = i0 - 1 if lines[i0 - 1].strip() == "xdef\t" + a.first else i0
    end = i1 + 1
    while end < len(lines) and not re.match(r"^\s*xdef\b", lines[end]) \
            and not re.match(r"^[A-Za-z_][A-Za-z0-9_]*:", lines[end]):
        end += 1

    body = lines[start:end]
    n = sum(len(l.split("dc.b", 1)[1].split(",")) for l in body if "dc.b" in l)
    n += 4 * sum(len(l.split("dc.l", 1)[1].split(",")) for l in body if "dc.l" in l)

    out = ["; GENERATED by tools/oracle/extract_data_slice.py",
           "; slice %s .. %s of %s -- %d bytes"
           % (a.first, a.last, os.path.basename(a.src), n),
           "; DO NOT EDIT: regenerate after any change to the storage manifest.",
           "",
           "\tsection\tffedat,data",
           ""] + body + [""]
    io.open(a.out, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print("wrote %s (%d lines, %d bytes of data)" % (a.out, len(body), n))
    return 0


if __name__ == "__main__":
    sys.exit(main())
