"""Generates amiga/music/softclip.h: 16-bit sample >> 6 (1024 steps) -> 8-bit
Paula sample with gain and a soft knee (tanh), so the music can be played
louder without hard clipping on its peaks (2026-10-24: at unity gain the
streams peaked at half scale and the music was barely audible).
    python make_softclip.py [GAIN]      (default 2.5)"""
import math
import os
import sys

gain = float(sys.argv[1]) if len(sys.argv) > 1 else 2.5
norm = math.tanh(gain)
vals = []
for i in range(1024):
    x = (i - 512) / 512.0                     # -1 .. +1
    y = math.tanh(gain * x) / norm            # same slope near 0 = gain, saturates at 1
    vals.append(max(-128, min(127, int(round(y * 127)))))
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "amiga", "music", "softclip.h")
with open(out, "w", newline="\n") as f:
    f.write("/* SPDX-License-Identifier: MIT\n * Copyright (c) 2026 angree. See LICENSE at the repository root.\n *\n")
    f.write(" * GENERATED by tools/music/make_softclip.py (gain %.2f): index = (sample16 + 32768) >> 6,\n" % gain)
    f.write(" * value = the 8-bit Paula sample, gain with a tanh knee. Do not edit. */\n")
    f.write("static const signed char ffe_softclip[1024] = {\n")
    for k in range(0, 1024, 16):
        f.write("\t" + ", ".join("%4d" % v for v in vals[k:k + 16]) + ",\n")
    f.write("};\n")
print("wrote", out, "gain", gain, "slope at 0:", vals[513] - vals[511], "/2 steps")
